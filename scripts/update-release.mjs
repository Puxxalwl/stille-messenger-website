import { writeFile } from 'node:fs/promises';

const repo = 'Puxxalwl/Stille-Messenger-Android';
const fallback = { version: '3.4.0', apk: 'https://github.com/Puxxalwl/Stille-Messenger-Android/releases/download/v3.4.0/Stille-Messenger-v3.4.0.apk' };
let releases;
try {
  const response = await fetch(`https://api.github.com/repos/${repo}/releases?per_page=30`, { headers: { accept: 'application/vnd.github+json', 'user-agent': 'stille-messenger-website' } });
  if (!response.ok) throw new Error(`GitHub Releases request failed: ${response.status}`);
  releases = await response.json();
} catch (error) {
  console.warn(`Could not query GitHub Releases; retaining ${fallback.version}: ${error.message}`);
  releases = [];
}
const release = releases.find((item) => !item.draft && !item.prerelease && item.assets?.some((asset) => asset.name.toLowerCase().endsWith('.apk')));
if (!release) {
  await writeFile(new URL('../src/lib/release.generated.ts', import.meta.url), `// Generated fallback; update-release.mjs queries GitHub Releases on each build.\nexport const release = ${JSON.stringify(fallback, null, 2)} as const;\n`);
  console.log(`Using Android release ${fallback.version}`);
  process.exit(0);
}
const asset = release.assets.find((item) => item.name.toLowerCase().endsWith('.apk'));
const version = release.tag_name.replace(/^v/, '');
const content = `// Generated by scripts/update-release.mjs; do not edit by hand.\nexport const release = ${JSON.stringify({ version, apk: asset.browser_download_url }, null, 2)} as const;\n`;
await writeFile(new URL('../src/lib/release.generated.ts', import.meta.url), content);
console.log(`Selected Android release ${release.tag_name}: ${asset.name}`);
